export const dictionaries: Record<Language, Messages> = { en, fr };

export function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && (languages as string[]).includes(value);
}

export function loadLanguage(): Language {
  try {
    const stored = localStorage.getItem(languageStorageKey);
    return isLanguage(stored) ? stored : defaultLanguage;
  } catch {
    return defaultLanguage;
  }
}

export function saveLanguage(language: Language) {
  try {
    localStorage.setItem(languageStorageKey, language);
  } catch {
    // Storage can be unavailable (private mode, blocked site data); the choice then lasts for this session only.
  }
}
